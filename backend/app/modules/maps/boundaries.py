def get_village_boundary(name_gu: str, code: str) -> Optional[Dict]:
    """Retrieve verified village boundary polygon GeoJSON if available."""
    # Direct match on name_gu
    if name_gu in BOTAD_VILLAGE_BOUNDARIES:
        return BOTAD_VILLAGE_BOUNDARIES[name_gu]

    # Partial match on standard village name components
    for key, boundary in BOTAD_VILLAGE_BOUNDARIES.items():
        if key in name_gu or name_gu in key:
            return boundary

    return None

